#!/usr/bin/env python3
"""The agent release this repository pins (packages/letkite-agent/files/release).

    scripts/release-table.py check            # the pinned table matches its signed release
    scripts/release-table.py latest           # print the stable channel's version
    scripts/release-table.py write VERSION    # verify VERSION and write the table

A release is trusted only if its release.json verifies with one of the agent
release keys in keys/agent-release-keys.txt (Ed25519; the signature covers
"letkite-release-v1\\n" followed by release.json's bytes), names the product
letkite-agent and the version asked for, and if SHA256SUMS from the same
release agrees with release.json for every program the table lists. The
signature is checked with the openssl command (OpenSSL 3).

Only the standard library and openssl: this runs in CI with nothing installed.
"""

import base64
import json
import os
import re
import subprocess
import sys
import tempfile
import urllib.error
import urllib.request

# Tests only: another site, key list and table.
SITE = os.environ.get("LETKITE_RELEASE_SITE", "https://get.letkite.com")
REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KEYS = os.environ.get("LETKITE_RELEASE_KEYS", os.path.join(REPO, "keys", "agent-release-keys.txt"))
TABLE = os.environ.get("LETKITE_RELEASE_TABLE", os.path.join(REPO, "packages", "letkite-agent", "files", "release"))
SIGNED_PREFIX = b"letkite-release-v1\n"
# the table's architecture names -> release.json's platforms
ARCHES = {"x86_64": "linux-x86_64", "arm64": "linux-arm64", "armv7": "linux-armv7"}
# the router build of each (letkite/letkite#530: without the desktop, within
# a router's flash budget), letkite-agent-router-linux-<arch>; releases from
# before it have the full build only
ROUTER = "router-"
# releases this package pins: X.Y.Z only (opkg and apk order pre-releases
# differently from semver, and the stable channel has none)
VERSION = re.compile(r"^(0|[1-9][0-9]{0,3})\.(0|[1-9][0-9]{0,3})\.(0|[1-9][0-9]{0,3})$")
# Ed25519 SubjectPublicKeyInfo, before the 32 key bytes
ED25519_SPKI = bytes.fromhex("302a300506032b6570032100")

HEADER = """\
# The LetKite agent release this package installs: its version, and the file,
# size and SHA-256 of the program for each architecture (the router build,
# or the full one in releases before it). Generated by
# scripts/release-table.py from the release's signed release.json and its
# SHA256SUMS (see .github/workflows/bump.yml); do not edit by hand.
# shellcheck disable=SC2034 # read by fetch.sh, by name
"""


class Untrusted(Exception):
    pass


def fetch(url, limit=1 << 20):
    req = urllib.request.Request(url, headers={"User-Agent": "letkite-router-release-table"})
    with urllib.request.urlopen(req, timeout=60) as r:
        data = r.read(limit + 1)
    if len(data) > limit:
        raise Untrusted(f"{url} is larger than {limit} bytes")
    return data


def keys():
    out = []
    with open(KEYS) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            raw = base64.b64decode(line, validate=True)
            if len(raw) != 32:
                raise SystemExit(f"{KEYS}: not an Ed25519 public key: {line}")
            out.append(raw)
    if not out:
        raise SystemExit(f"{KEYS}: no keys")
    return out


def verify_signature(manifest, signature_b64):
    try:
        sig = base64.b64decode(signature_b64.strip(), validate=True)
    except ValueError as e:
        raise Untrusted(f"release.json.sig is not base64: {e}")
    if len(sig) != 64:
        raise Untrusted("release.json.sig is not an Ed25519 signature (64 bytes)")
    with tempfile.TemporaryDirectory() as tmp:
        msg = os.path.join(tmp, "msg")
        sigf = os.path.join(tmp, "sig")
        with open(msg, "wb") as f:
            f.write(SIGNED_PREFIX + manifest)
        with open(sigf, "wb") as f:
            f.write(sig)
        for i, key in enumerate(keys()):
            pem = os.path.join(tmp, f"key{i}.pem")
            with open(pem, "w") as f:
                f.write("-----BEGIN PUBLIC KEY-----\n")
                f.write(base64.b64encode(ED25519_SPKI + key).decode() + "\n")
                f.write("-----END PUBLIC KEY-----\n")
            r = subprocess.run(
                ["openssl", "pkeyutl", "-verify", "-pubin", "-inkey", pem,
                 "-rawin", "-in", msg, "-sigfile", sigf],
                capture_output=True,
            )
            if r.returncode == 0:
                return base64.b64encode(key).decode()
    raise Untrusted("release.json's signature does not verify with any agent release key")


def parse_sums(text):
    sums = {}
    for line in text.splitlines():
        m = re.match(r"^([0-9a-f]{64}) [ *]?(\S+)$", line.strip())
        if m:
            sums[m.group(2)] = m.group(1)
    return sums


def table_for(version):
    """The table for VERSION, from its verified release."""
    if not VERSION.match(version):
        raise Untrusted(f"{version!r} is not a release version (X.Y.Z)")
    base = f"{SITE}/agent/v{version}"
    manifest = fetch(f"{base}/release.json", 64 * 1024)
    key = verify_signature(manifest, fetch(f"{base}/release.json.sig", 4096).decode("ascii", "replace"))
    m = json.loads(manifest)
    if m.get("product") != "letkite-agent":
        raise Untrusted(f"release.json is for {m.get('product')!r}, not letkite-agent")
    if m.get("version") != version:
        raise Untrusted(f"release.json is version {m.get('version')!r}, not {version}")
    sums = parse_sums(fetch(f"{base}/SHA256SUMS").decode("utf-8", "replace"))
    rows = {}
    artifacts = m.get("artifacts") or {}
    for arch, full in ARCHES.items():
        platform = ROUTER + full if ROUTER + full in artifacts else full
        a = artifacts.get(platform)
        if not a:
            raise Untrusted(f"release.json has no {full}")
        file, sha, size = a.get("file"), a.get("sha256"), a.get("size")
        if file != f"letkite-agent-{platform}":
            raise Untrusted(f"release.json: {platform} is {file!r}")
        if not (isinstance(sha, str) and re.fullmatch(r"[0-9a-f]{64}", sha)):
            raise Untrusted(f"release.json: bad SHA-256 for {platform}")
        if not (isinstance(size, int) and 0 < size < 512 * 1024 * 1024):
            raise Untrusted(f"release.json: bad size for {platform}")
        if sums.get(file) != sha:
            raise Untrusted(f"SHA256SUMS does not match release.json for {file}")
        rows[arch] = (file, sha, size)
    return key, rows


def render(version, rows):
    out = [HEADER, f"AGENT_VERSION={version}\n"]
    for arch in ARCHES:
        file, sha, size = rows[arch]
        out.append(f"AGENT_FILE_{arch}={file}\nAGENT_SHA256_{arch}={sha}\nAGENT_SIZE_{arch}={size}\n")
    return "".join(out)


def pinned():
    with open(TABLE) as f:
        text = f.read()
    m = re.search(r"^AGENT_VERSION=(\S+)$", text, re.M)
    if not m:
        raise SystemExit(f"{TABLE}: no AGENT_VERSION")
    return m.group(1), text


def newer(a, b):
    return tuple(map(int, a.split("."))) > tuple(map(int, b.split(".")))


def main(argv):
    cmd = argv[1] if len(argv) > 1 else ""
    try:
        if cmd == "check":
            version, text = pinned()
            key, rows = table_for(version)
            if text != render(version, rows):
                print(f"{TABLE} does not match the signed release {version}; "
                      f"run scripts/release-table.py write {version}", file=sys.stderr)
                return 1
            print(f"{version}: the pinned table matches the release, signed by {key}")
        elif cmd == "latest":
            channel = json.loads(fetch(f"{SITE}/channels/stable.json", 4096))
            version = channel.get("version", "")
            if not VERSION.match(version):
                raise Untrusted(f"the stable channel names {version!r}")
            print(version)
        elif cmd == "write" and len(argv) == 3:
            version = argv[2]
            key, rows = table_for(version)
            with open(TABLE, "w") as f:
                f.write(render(version, rows))
            print(f"{version}: verified (signed by {key}); wrote {os.path.relpath(TABLE, REPO)}")
        elif cmd == "newer" and len(argv) == 4:
            # exit 0 if argv[2] is newer than argv[3]
            return 0 if newer(argv[2], argv[3]) else 1
        elif cmd == "pinned":
            print(pinned()[0])
        else:
            print(__doc__.strip(), file=sys.stderr)
            return 2
    except Untrusted as e:
        print(f"release-table: refusing the release: {e}", file=sys.stderr)
        return 1
    except (urllib.error.URLError, ValueError) as e:
        print(f"release-table: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
